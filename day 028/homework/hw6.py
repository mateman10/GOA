# 6. count()

# შექმენი სია:
# ["car", "bike", "car", "bus", "plane", "car", "bike"]

# count() მეთოდის გამოყენებით დაითვალე:
# რამდენჯერ გვხვდება "car"
# რამდენჯერ გვხვდება "bike"

transports = ["car", "bike", "car", "bus", "plane", "car", "bike"]

print(transports.count("car"))
print(transports.count("bike"))