# 10. count() და index()

# შექმენი სია:
# ["python", "java", "c++", "python", "javascript"]

# count() მეთოდით დაითვალე რამდენჯერ გვხვდება "python", ხოლო index() მეთოდით იპოვე "c++"-ის ინდექსი. გამოიტანე ორივე შედეგი.

programming_languages = ["python", "java", "c++", "python", "javascript"]

print(programming_languages.count("python"))
print(programming_languages.index("c++"))