# 5) მოცემულია Tuple: `numbers = (2, 4, 6, 4, 8, 4, 10, 6, 4)`.
# `.count()` მეთოდის გამოყენებით დაითვალე, რამდენჯერ გვხვდება რიცხვი `4`.
# `.index()` მეთოდის გამოყენებით იპოვე, რომელ ინდექსზე დგას პირველად რიცხვი `6`.

numbers = (2, 4, 6, 4, 8, 4, 10, 6, 4)

print(numbers.count(4))
print(numbers.index(6))