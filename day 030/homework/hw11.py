# 11) შექმენი Tuple სახელად `person = ("ანა", 16, "ქუთაისი", "Python")`.
# Unpacking-ის გამოყენებით მნიშვნელობები მიანიჭე ოთხ ცვლადს: `name`, `age`, `city`, `language`.
# დაბეჭდე თითოეული ცვლადი ცალ-ცალკე.

person = ("ანა", 16, "ქუთაისი", "Python")

name, age, city, language = person

print(name)
print(age)
print(city)
print(language)