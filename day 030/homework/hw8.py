# 8) მოცემულია Tuple: `scores = (90, 75, 90, 60, 85, 90, 70)`.
# `.count()` მეთოდის გამოყენებით გაიგე, რამდენჯერ გვხვდება ქულა `90`.
# `.index()` მეთოდის გამოყენებით იპოვე, რომელ ინდექსზე დგას პირველად ქულა `75`.

scores = (90, 75, 90, 60, 85, 90, 70)

print(scores.count(90))
print(scores.index(75))