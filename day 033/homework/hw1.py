# გამოიყენე `union()` მეთოდი, რათა გააერთიანო ორივე Set. შემდეგ გამოიყენე `len()` 
# ფუნქცია და დაბეჭდე გაერთიანებულ Set-ში არსებული ელემენტების რაოდენობა.


