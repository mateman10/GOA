#2. მომხმარებელს შემოატანინე ასაკი.
#თუ ასაკი ნაკლებია 18-ზე, დაბეჭდე `"არასრულწლოვანი"`.
#თუ ასაკი 18-დან 64-მდეა, დაბეჭდე `"ზრდასრული"`.
#სხვა შემთხვევაში, დაბეჭდე `"პენსიონერი"`.

age = int(input('how old are you? '))

if age < 18:
    print('არასრულწლოვანი')
elif age <= 64:
    print('ზრდასრული')
else:
    print('პენსიონერი')