#3. მომხმარებელს შემოატანინე გამოცდის ქულა.
#თუ ქულა 90-100 შუალედშია, დაბეჭდე `"A"`.
#თუ ქულა 80-89 შუალედშია, დაბეჭდე `"B"`.
#თუ ქულა 70-79 შუალედშია, დაბეჭდე `"C"`.
#თუ ქულა 60-69 შუალედშია, დაბეჭდე `"D"`.
#სხვა შემთხვევაში, დაბეჭდე `"F"`.

point = int(input('whats ur point? '))

if point <= 100:
    print('A')
elif point <= 89:
    print('B')
elif point <= 79:
    print('C')
elif point <= 69:
    print('D')
else:
    print('F')