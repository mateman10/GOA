#1) მომხმარებელს შემოატანინე თავისი ასაკი და რიცხვი 18-თან შეადარე ოპერატორების (`>`, `<`, `>=`, `<=`, `!=`, `==`) გამოყენებით. თითოეული შედარების შედეგი ცალ-ცალკე დაბეჭდე.


age = int(input("how old are you? "))


print(age>18)

print(age<18)

print(age<=18)

print(age>=18)

print(age==18)

print(age!=18)

